// Prints SQL that loads the invented sample shelters.
// Run with `npm run seed:sql`, which writes supabase/seed.sql.
// The SQL overwrites existing sample shelters, so running it again resets the
// demo data, including each shelter's "last updated" time.
import { sampleShelters } from "../src/lib/sample-shelters";

const sqlString = (value: string) => `'${value.replaceAll("'", "''")}'`;

const rows = sampleShelters.map((s) =>
  [
    sqlString(s.name),
    sqlString(s.address),
    sqlString(s.phone),
    s.capacity,
    s.occupied,
    s.womenOnly,
    s.acceptsChildren,
    s.acceptsPets,
    s.requiresSobriety,
    `now() - interval '${s.minutesSinceLastUpdate} minutes'`,
  ].join(", "),
);

console.log(`-- Generated by scripts/generate-seed.ts from src/lib/sample-shelters.ts. Do not edit by hand.
-- Run again at any time (for example in the Supabase SQL editor) to reset the demo data.
insert into public.shelters
  (name, address, phone, capacity, occupied, women_only, accepts_children, accepts_pets, requires_sobriety, last_updated_at)
values
${rows.map((row) => `  (${row})`).join(",\n")}
on conflict (name) do update set
  address = excluded.address,
  phone = excluded.phone,
  capacity = excluded.capacity,
  occupied = excluded.occupied,
  women_only = excluded.women_only,
  accepts_children = excluded.accepts_children,
  accepts_pets = excluded.accepts_pets,
  requires_sobriety = excluded.requires_sobriety,
  closed_at = null,
  last_updated_at = excluded.last_updated_at;`);
